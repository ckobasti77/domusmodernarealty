import { createCn } from "cn/engine";
import tables from "./cn-tables";

/**
 * `cn` — clsx + Tailwind conflict resolution, fitted to THIS project's theme.
 *
 * The stock `cn` export cannot be used here. Its built-in tables only know
 * Tailwind's own scales, so it classifies every unknown `text-*` utility into a
 * single group — and this project has custom `text-*` font sizes
 * (`text-display-xl`, `text-h2`, `text-small`, `text-label`, …) alongside custom
 * `text-*` colours (`text-ink`, `text-mist`, `text-bronze`, …). The result was
 * silent: `cn("bg-ivory text-ink", "h-[52px] text-small")` dropped `text-ink`,
 * and the primary cookie-banner button rendered ivory-on-ivory.
 *
 * `lib/cn-tables.ts` is generated by `npm run cn:tables`, which reads the
 * `@theme` block in `app/globals.css` and therefore knows that `small` is a
 * font size and `ink` is a colour. Re-run it after adding a theme scale or a
 * new utility; the build is checked into git so no install step depends on it.
 */
export const cn = createCn(tables);
