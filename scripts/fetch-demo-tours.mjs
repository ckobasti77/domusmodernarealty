#!/usr/bin/env node
// Downloads the Poly Haven CC0 panoramas listed in docs/assets/demo-media.json
// and turns them into the self-hosted demo 360° tour (docs/06-3D-TOURS.md).
//
// Usage: node scripts/fetch-demo-tours.mjs [--force]
//
//   media-src/tours/<id>.jpg                        original 8K download (gitignored)
//   public/media/tours/demo/<id>-4096.jpg           desktop panorama, 4096×2048
//   public/media/tours/demo/<id>-2048.jpg           mobile panorama, 2048×1024
//   public/media/tours/demo/<id>-thumb.jpg          512×256 gallery thumbnail
//   convex/seed/tours.generated.ts                  paths + sizes for the seed
//
// Idempotent: a download is skipped when the original exists, an output is
// rebuilt only when missing or with --force. Fails when the committed outputs
// would exceed the 25 MB budget (IMPLEMENTATION-PLAN step 11).
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, "media-src", "tours");
const OUT_DIR = path.join(ROOT, "public", "media", "tours", "demo");
const PUBLIC_PREFIX = "/media/tours/demo";
const GENERATED = path.join(ROOT, "convex", "seed", "tours.generated.ts");
const BUDGET_BYTES = 25 * 1024 * 1024;

const VARIANTS = [
  { key: "desktop", suffix: "4096", width: 4096, height: 2048, quality: 86 },
  { key: "mobile", suffix: "2048", width: 2048, height: 1024, quality: 82 },
  { key: "thumb", suffix: "thumb", width: 512, height: 256, quality: 78 },
];

const force = process.argv.includes("--force");

function mb(bytes) {
  return `${(bytes / 1_048_576).toFixed(1)} MB`;
}

async function download(url, file) {
  if (existsSync(file) && statSync(file).size > 0) return;
  process.stdout.write(`  downloading ${url}\n`);
  const response = await fetch(url, { headers: { "User-Agent": "mihajlo-estate demo-tour fetcher" } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  await writeFile(file, Buffer.from(await response.arrayBuffer()));
}

async function main() {
  const media = JSON.parse(readFileSync(path.join(ROOT, "docs", "assets", "demo-media.json"), "utf8"));
  const panoramas = media.panoramas ?? [];
  if (panoramas.length === 0) throw new Error("demo-media.json lists no panoramas");

  mkdirSync(SRC_DIR, { recursive: true });
  mkdirSync(OUT_DIR, { recursive: true });

  const entries = [];
  let total = 0;
  for (const pano of panoramas) {
    if (pano.license !== "CC0") throw new Error(`${pano.id}: only CC0 panoramas may be committed`);
    process.stdout.write(`${pano.id}\n`);
    const original = path.join(SRC_DIR, `${pano.id}.jpg`);
    await download(pano.url, original);
    const meta = await sharp(original).metadata();
    if (meta.width !== 2 * meta.height) {
      throw new Error(`${pano.id}: not an equirectangular 2:1 image (${meta.width}×${meta.height})`);
    }

    const files = {};
    for (const variant of VARIANTS) {
      const name = `${pano.id}-${variant.suffix}.jpg`;
      const out = path.join(OUT_DIR, name);
      if (force || !existsSync(out)) {
        await sharp(original, { limitInputPixels: false })
          .resize(variant.width, variant.height, { fit: "fill", kernel: "lanczos3" })
          .jpeg({ quality: variant.quality, mozjpeg: true, progressive: true })
          .toFile(out);
      }
      const bytes = statSync(out).size;
      total += bytes;
      files[variant.key] = { url: `${PUBLIC_PREFIX}/${name}`, bytes };
      process.stdout.write(`  ${name.padEnd(36)} ${mb(bytes)}\n`);
    }
    entries.push({ id: pano.id, page: pano.page, license: pano.license, ...files });
  }

  process.stdout.write(`\ncommitted panoramas: ${mb(total)} (budget ${mb(BUDGET_BYTES)})\n`);
  if (total > BUDGET_BYTES) throw new Error("over the 25 MB budget: drop scenes or lower the quality");

  const body = `// Generated by scripts/fetch-demo-tours.mjs. Do not edit by hand.
// Poly Haven CC0 panoramas, optimized and served from public/.

export type DemoPanoramaFile = { url: string; bytes: number };
export type DemoPanorama = {
  id: string;
  page: string;
  license: "CC0";
  desktop: DemoPanoramaFile;
  mobile: DemoPanoramaFile;
  thumb: DemoPanoramaFile;
};

export const DEMO_TOUR_PANORAMAS: DemoPanorama[] = ${JSON.stringify(entries, null, 2)};
`;
  writeFileSync(GENERATED, body);
  process.stdout.write(`wrote ${path.relative(ROOT, GENERATED)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
